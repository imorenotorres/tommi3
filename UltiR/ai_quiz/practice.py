"""Practice ("Practicar"): a student chooses a topic or a level, gets one exercise at a time, answers
it in their own words and gets feedback on it.

This is formative practice and follows its own rule: exercises and feedback reach students as the
model writes them, without an instructor reading them first. What stands in for that reading is
the checks in code (exercise_types, feedback), the label "generated by AI from the handout" on
every exercise, the student's "Report a problem", and the instructor's list of every exercise with
"retire" and "approve". Quizzes keep their rule: nothing reaches students unpublished.

Layout inside a course folder:

    practice/settings.json      {"enabled": bool, "topics": {topic_id: {"enabled": bool, "name": str}}}
    practice/exercises/ ...     the exercises and what is recorded about them (exercises.py)
    practice/students/ ...      each student's own record, under a keyed hash (progress.py)

Practice exists on a server only when config.practice_enabled(), and in a course only once its
instructor switches it on.
"""

import time

from UltiR.ai_quiz import (
    config, documents, exercise_types, exercises, feedback, limits, programmed, progress, schema, storage, topics, tutors,
)
from UltiR.ai_quiz.mathflag import has_math_notation

MAX_TOPIC_NAME_CHARS = 80
LEVELS = ("basico", "intermedio", "avanzado")


class PracticeError(Exception):
    def __init__(self, status: int, code: str, **extra):
        super().__init__(code)
        self.status = status
        self.code = code
        self.extra = extra


def _dir(course_id: str):
    return storage.course_dir(course_id) / "practice"


# ── Settings (instructor) ─────────────────────────────────────────────────────

def _settings_path(course_id: str):
    return _dir(course_id) / "settings.json"


def settings(course_id: str) -> dict:
    stored = storage.read_json(_settings_path(course_id), default={}) or {}
    return {"enabled": stored.get("enabled") is True, "topics": stored.get("topics") or {}}


def _merged(course_id: str) -> list[dict]:
    """Every topic found in the course's documents, with what the instructor set for it.

    A topic is on unless the instructor turned it off. Its name is the instructor's, or the
    heading it was found under; a topic made of a range of pages has no name of its own.
    """
    chosen = settings(course_id)["topics"]
    merged = []
    for topic in topics.course_topics(course_id):
        own = chosen.get(topic["topic_id"]) or {}
        merged.append({**topic, "enabled": own.get("enabled") is not False, "name": own.get("name") or topic["title"]})
    return merged


def instructor_settings(course_id: str) -> dict:
    return {
        "enabled": settings(course_id)["enabled"],
        "topics": [{key: topic[key] for key in ("topic_id", "doc_label", "title", "name", "kind", "pages", "enabled")}
                   for topic in _merged(course_id)],
    }


def change_settings(course_id: str, body: dict) -> dict:
    """Switch practice on or off, and topics on or off or rename them. Reads `enabled` and `topics` only.

    `topics` maps a topic id to {"enabled": bool, "name": str}, each optional; an empty name gives
    the topic back the name it was found under. A topic id that is not a topic of the course is refused.
    """
    enabled = body.get("enabled")
    if enabled is not None and not isinstance(enabled, bool):
        raise PracticeError(400, "bad_request", field="enabled")
    changes = body.get("topics", {})
    if not isinstance(changes, dict) or not all(isinstance(c, dict) for c in changes.values()):
        raise PracticeError(400, "bad_request", field="topics")
    if enabled is None and not changes:
        raise PracticeError(400, "bad_request", field="enabled")
    with storage.locked(course_id):
        known = {topic["topic_id"] for topic in topics.course_topics(course_id)}
        if not set(changes) <= known:
            raise PracticeError(404, "unknown_topic")
        current = settings(course_id)
        for topic_id, change in changes.items():
            own = dict(current["topics"].get(topic_id) or {})
            if "enabled" in change:
                if not isinstance(change["enabled"], bool):
                    raise PracticeError(400, "bad_request", field="topics")
                own["enabled"] = change["enabled"]
            if "name" in change:
                try:
                    own["name"] = schema.clean_text(change["name"], MAX_TOPIC_NAME_CHARS, required=False)
                except schema.InvalidQuestion:
                    raise PracticeError(400, "bad_request", field="topics") from None
            current["topics"][topic_id] = own
        if enabled is not None:
            current["enabled"] = enabled
        storage.write_json(_settings_path(course_id), current)
    return instructor_settings(course_id)


# ── What a student may see ────────────────────────────────────────────────────

def require_open(course_id: str) -> None:
    """Practice is on in this course, or PracticeError."""
    if not settings(course_id)["enabled"]:
        raise PracticeError(409, "practice_off")


def open_topics(course_id: str) -> list[dict]:
    """The topics a student can choose: those that are on, with their name, document and pages.

    Without run-time model use (config.practice_model_enabled), only a topic that a programmed tutor serves is
    offered: nothing else could be practised without asking a model.
    """
    topics_on = [topic for topic in _merged(course_id) if topic["enabled"]]
    if config.practice_model_enabled():
        return topics_on
    served = programmed_topics(course_id)
    return [topic for topic in topics_on if topic["topic_id"] in served]


def programmed_topics(course_id: str) -> set[str]:
    """The ids of the topics a programmed tutor serves in this course (programmed.py)."""
    return set(programmed.topic_tutors(course_id))


def _require_model(exercise: dict) -> None:
    """A model-written exercise can be practised only while run-time model use is on."""
    if exercise.get("type") != "programado" and not config.practice_model_enabled():
        raise PracticeError(409, "model_practice_off")


def student_topics(course_id: str) -> list[dict]:
    require_open(course_id)
    return [{key: topic[key] for key in ("topic_id", "name", "doc_label", "pages")} for topic in open_topics(course_id)]


def server_offers_practice() -> bool:
    return config.practice_enabled()


# ── One exercise for a student ────────────────────────────────────────────────

def _lookup(course_id: str):
    """exercise id -> the stored exercise of this course, read once per request."""
    cache = {}

    def find(exercise_id):
        if exercise_id not in cache:
            cache[exercise_id] = exercises.load(course_id, exercise_id)
        return cache[exercise_id]
    return find


def _language(body: dict) -> str:
    language = body.get("language", "es")
    if not isinstance(language, str) or language not in exercises.LANGUAGES:
        raise PracticeError(400, "bad_request", field="language")
    return language


def _owner(course_id: str, user_id: str) -> str:
    if not user_id:
        raise PracticeError(400, "no_user")
    return progress.owner(course_id, user_id)


def _reserve(course_id: str, owner: str, preview: bool) -> None:
    """Count one exercise against the student's daily limit, or PracticeError. Given back if none is served."""
    with storage.locked(course_id):
        record = progress.load(course_id, owner)
        day, limit = progress.today(), config.practice_daily_limit()
        if record["days"].get(day, 0) >= limit:
            raise PracticeError(429, "daily_limit", limit=limit)
        record["days"] = {day: record["days"].get(day, 0) + 1}      # only today's count is kept
        record["preview"] = record["preview"] or preview
        progress.save(course_id, owner, record)


def _give_back(course_id: str, owner: str) -> None:
    with storage.locked(course_id):
        record = progress.load(course_id, owner)
        day = progress.today()
        record["days"][day] = max(0, record["days"].get(day, 0) - 1)
        progress.save(course_id, owner, record)


def _hand_out(course_id: str, owner: str, exercise: dict) -> None:
    """Note in the student's record that they were given this exercise, and count it as served once more."""
    with storage.locked(course_id):
        record = progress.load(course_id, owner)
        record["exercises"][exercise["exercise_id"]] = {
            "exercise_id": exercise["exercise_id"], "topic_id": exercise["topic_id"], "level": exercise["level"],
            "type": exercise["type"], "served_at": exercises.now(), "tries": [], "solution": False, "reported": False}
        progress.save(course_id, owner, record)
        exercises.count_served(course_id, exercise["exercise_id"])


async def next_exercise(course_id: str, user_id: str, preview: bool, body: dict) -> dict:
    """One exercise for the student, of the topic and level they chose or chosen for them: from the pool
    when it has one they have not had, otherwise written now. Reads `topic_id`, `level` and `language` only."""
    require_open(course_id)
    owner = _owner(course_id, user_id)
    language = _language(body)
    topic_id, level = body.get("topic_id"), body.get("level")
    if topic_id is not None and not isinstance(topic_id, str):
        raise PracticeError(400, "bad_request", field="topic_id")
    if level is not None and level not in LEVELS:
        raise PracticeError(400, "bad_request", field="level")
    offered = open_topics(course_id)
    if not offered:
        raise PracticeError(409, "no_topics")
    record, lookup = progress.load(course_id, owner), _lookup(course_id)
    chosen = {"topic": "yours" if topic_id is not None else "for_you", "level": "yours" if level is not None else "for_you"}
    if topic_id is None:
        topic = progress.choose_topic(record, offered, lookup)
    else:
        topic = next((t for t in offered if t["topic_id"] == topic_id), None)
        if topic is None:
            raise PracticeError(404, "unknown_topic")
    if level is None:
        level = progress.choose_level(record, topic["topic_id"])
    aim = progress.target(record, topic["topic_id"], lookup)
    aimed = aim["text"] if aim else None
    seen = set(record["exercises"])

    served_by = programmed.topic_tutors(course_id).get(topic["topic_id"])
    if served_by:
        # A programmed tutor: an exercise made from a seed, aimed at the mistake of the student's last exercise on
        # the topic. No model, no pool.
        last = progress.last_mistake(record, topic["topic_id"])
        _reserve(course_id, owner, preview)
        try:
            exercise = programmed.new_exercise(course_id, topic, served_by, level, language, last)
        except BaseException:
            _give_back(course_id, owner)
            raise
        _hand_out(course_id, owner, exercise)
        return {"exercise": exercises.learner_view(exercise),
                "topic": {"topic_id": topic["topic_id"], "name": topic["name"], "pages": topic["pages"]},
                "chosen": chosen, "aim": "mistake_last" if last and last in exercise["wrong"] else None}

    _reserve(course_id, owner, preview)
    try:
        if not config.practice_model_enabled():
            raise PracticeError(409, "model_practice_off")
        exercise = exercises.from_pool(course_id, topic["topic_id"], level, language, seen, aimed)
        if exercise is not None:
            exercises.record_run(course_id, "exercise", 0, 0.0, "pool")
        else:
            wait = exercises.take_run(course_id)
            if wait:
                raise PracticeError(429, "practice_busy", retry_after_seconds=wait)
            chunks = topics.topic_chunks(course_id, topic)
            if not chunks:
                raise PracticeError(409, "no_text_in_topic")
            try:
                exercise = await exercises.write(course_id, topic, chunks, level, progress.kind_for(record, topic["topic_id"]),
                                                 language, aimed, exercises.statements(course_id, topic["topic_id"]))
            except exercises.ExerciseFailed as failed:
                # Nothing new could be written. One of the pool that does not aim at the point is better than none.
                exercise = exercises.from_pool(course_id, topic["topic_id"], level, language, seen, None) if aimed else None
                if exercise is None:
                    raise PracticeError(failed.status, failed.code) from None
                aim = None
    except BaseException:
        _give_back(course_id, owner)
        raise
    _hand_out(course_id, owner, exercise)
    return {"exercise": exercises.learner_view(exercise), "topic": {"topic_id": topic["topic_id"], "name": topic["name"],
                                                                     "pages": topic["pages"]},
            "chosen": chosen, "aim": aim["kind"] if aim else None}


# ── Answering ─────────────────────────────────────────────────────────────────

def _review(exercise: dict) -> dict:
    """What to read again: the document, the page, and the passage when it reads as plain prose."""
    source = exercise["source"]
    quoted = not has_math_notation(source.get("excerpt") or "")
    return {"doc_label": source.get("doc_label"), "page": source.get("page"),
            "excerpt": source.get("excerpt") if quoted else None}


def _chunk_text(course_id: str, exercise: dict) -> str:
    """The whole chunk of the handout the exercise's passage is in, or "" if its document is gone."""
    source = exercise["source"]
    return next((c["text"] for c in documents.load_chunks(course_id, source.get("doc_id") or "")
                 if c["chunk_id"] == source.get("chunk_id")), "")


def _may_see_solution(entry: dict) -> bool:
    tries = entry["tries"]
    return bool(tries) and (tries[-1]["verdict"] == "correcto" or len(tries) >= limits.MAX_PRACTICE_TRIES)


async def answer(course_id: str, user_id: str, exercise_id: str, body: dict) -> dict:
    """Feedback on one try. Reads `answer`, `value` (numerical exercises) and `language` only."""
    require_open(course_id)
    owner = _owner(course_id, user_id)
    language = _language(body)
    exercise, entry = _entry(course_id, owner, exercise_id)
    _require_model(exercise)
    if len(entry["tries"]) >= limits.MAX_PRACTICE_TRIES or (entry["tries"] and entry["tries"][-1]["verdict"] == "correcto"):
        raise PracticeError(409, "no_more_tries")
    if exercise["type"] == programmed.KIND:
        return _answer_programmed(course_id, owner, exercise, entry, body, language)
    try:
        text = feedback.clean_answer(body.get("answer"))
        given = exercise_types.TYPES[exercise["type"]].given(body, exercise)
    except feedback.AnswerRefused as refused:
        raise PracticeError(refused.status, refused.code) from None
    except exercise_types.InvalidExercise:
        raise PracticeError(400, "bad_value") from None
    if exercise["type"] == "numerica" and given.get("value") is None:
        raise PracticeError(400, "value_missing")
    if exercise["type"] != "numerica" and not text:
        raise PracticeError(400, "answer_missing")
    wait = exercises.take_run(course_id)
    if wait:
        raise PracticeError(429, "practice_busy", retry_after_seconds=wait)

    record, lookup = progress.load(course_id, owner), _lookup(course_id)
    history = progress.misses(record, exercise["topic_id"], lookup)
    number = len(entry["tries"]) + 1
    started = time.monotonic()
    try:
        got = await feedback.give(exercise, text, given, number, history, language, exercises.ask,
                                  _chunk_text(course_id, exercise))
    except ValueError:
        raise PracticeError(503, "model_unavailable") from None
    seconds = time.monotonic() - started
    exercises.record_run(course_id, "feedback", got["calls"], seconds, "ai" if got["ai"] else "fallback", got["rejected"])

    kept = {"verdict": got["verdict"], "ai": got["ai"], "mistake": got["mistake"], "at": exercises.now(),
            "statuses": {kid: said["status"] for kid, said in (got["statuses"] or {}).items()},
            "checks": got["rejected"]}
    with storage.locked(course_id):
        record = progress.load(course_id, owner)
        mine = record["exercises"].get(exercise_id)
        if mine is None or len(mine["tries"]) != number - 1:
            raise PracticeError(409, "answered_meanwhile")
        mine["tries"].append(kept)
        progress.save(course_id, owner, record)

    points = []
    for point in exercise["key_points"]:
        said = (got["statuses"] or {}).get(point["id"]) or {}
        points.append({"id": point["id"], "text": point["text"], "status": said.get("status"), "evidence": said.get("evidence") or ""})
    mistake = next(({"id": m["id"], "text": m["text"]} for m in exercise["typical_mistakes"] if m["id"] == got["mistake"]), None)
    result = {
        "exercise_id": exercise_id, "try": number, "verdict": got["verdict"], "ai": got["ai"], "uncertain": got["uncertain"],
        "key_points": points, "mistake": mistake, "feedback": got["feedback"], "next_step": got["next_step"],
        "review": _review(exercise),
        "can_retry": got["verdict"] != "correcto" and number < limits.MAX_PRACTICE_TRIES,
        "can_see_solution": _may_see_solution(mine),
        "level_suggestion": progress.level_suggestion(record, exercise["topic_id"], exercise["level"]),
    }
    if exercise["type"] == "numerica":
        result["numeric"] = {"given": given["value"], "given_text": given["typed"],
                             "right": got["verdict"] == "correcto"}
    return result


def _answer_programmed(course_id: str, owner: str, exercise: dict, entry: dict, body: dict, language: str) -> dict:
    """A try at a programmed tutor's exercise: read the value, diagnose it, compose the feedback from the spec.

    Only `value` is read; a text the page may send is not read, kept or sent anywhere. No model is asked.
    """
    try:
        value, typed = programmed.read_value(exercise, body)
    except ValueError:
        raise PracticeError(400, "bad_value") from None
    if value is None:
        raise PracticeError(400, "value_missing")
    got = programmed.feedback(course_id, exercise, value, typed, language)
    number = len(entry["tries"]) + 1
    kept = {"verdict": got["verdict"], "ai": False, "programmed": True, "mistake": got["mistake"], "at": exercises.now(),
            "statuses": {}, "checks": []}
    with storage.locked(course_id):
        record = progress.load(course_id, owner)
        mine = record["exercises"].get(exercise["exercise_id"])
        if mine is None or len(mine["tries"]) != number - 1:
            raise PracticeError(409, "answered_meanwhile")
        mine["tries"].append(kept)
        progress.save(course_id, owner, record)
    return {
        "exercise_id": exercise["exercise_id"], "try": number, "verdict": got["verdict"], "ai": False,
        "programmed": True, "uncertain": False, "key_points": [],
        "mistake": {"id": got["mistake"], "text": got["mistake_title"]} if got["mistake"] else None,
        "feedback": got["feedback"], "next_step": got["next_step"], "review": got["review"],
        "can_retry": got["verdict"] != "correcto" and number < limits.MAX_PRACTICE_TRIES,
        "can_see_solution": _may_see_solution(mine),
        "level_suggestion": progress.level_suggestion(record, exercise["topic_id"], exercise["level"]),
        "numeric": {"given": value, "given_text": typed, "right": got["verdict"] == "correcto"},
    }


def solution(course_id: str, user_id: str, exercise_id: str) -> dict:
    """The reference solution, once the student got it right or used every try. Not before."""
    require_open(course_id)
    owner = _owner(course_id, user_id)
    with storage.locked(course_id):
        exercise, entry = _entry(course_id, owner, exercise_id)
        if not _may_see_solution(entry):
            raise PracticeError(409, "solution_not_yet")
        record = progress.load(course_id, owner)
        record["exercises"][exercise_id]["solution"] = True
        progress.save(course_id, owner, record)
    shown = {"exercise_id": exercise_id, "reference_solution": exercise["reference_solution"],
             "key_points": exercise["key_points"], "review": _review(exercise)}
    if exercise["type"] == "numerica":
        value = exercise["answer"].get("checked_value", exercise["answer"]["value"])
        shown.update(value=value, value_text=exercise_types.shown(value), unit=exercise["answer"].get("unit") or "")
    if exercise["type"] == programmed.KIND:
        value = exercise["solution_value"]
        places = 3 if exercise["form"] == "fraction3" else None
        shown.update(value=value, value_text=tutors.number(value, exercise.get("language", "es"), places), unit="")
    return shown


def open_exercise(course_id: str, user_id: str) -> dict:
    """The student's most recent exercise that is not finished, so that they can go on with it after closing the
    window: not answered right, a try left, not reported, still in use. {"exercise": None} if there is none."""
    require_open(course_id)
    owner = _owner(course_id, user_id)
    record = progress.load(course_id, owner)
    # newest first; two given within the same second keep the order they were given in (the later one first)
    for entry in sorted(list(record["exercises"].values())[::-1], key=lambda e: e["served_at"], reverse=True):
        tries = entry["tries"]
        if entry["reported"] or len(tries) >= limits.MAX_PRACTICE_TRIES or (tries and tries[-1]["verdict"] == "correcto"):
            continue
        exercise = exercises.load(course_id, entry["exercise_id"])
        if exercise is None or exercise["status"] != "servido":
            continue
        if exercise["type"] != "programado" and not config.practice_model_enabled():
            continue
        topic = next((t for t in _merged(course_id) if t["topic_id"] == exercise["topic_id"]), None)
        return {"exercise": exercises.learner_view(exercise), "tries": len(tries),
                "topic": {"topic_id": exercise["topic_id"], "name": topic["name"] if topic else None,
                          "pages": topic["pages"] if topic else None}}
    return {"exercise": None}


# ── Reporting ─────────────────────────────────────────────────────────────────

def _entry(course_id: str, owner: str, exercise_id: str) -> tuple[dict, dict]:
    """The exercise and the student's own line for it, or 404: an exercise the student was not given is not theirs."""
    exercise = exercises.load(course_id, exercise_id)
    entry = progress.load(course_id, owner)["exercises"].get(exercise_id) if exercise else None
    if entry is None:
        raise PracticeError(404, "exercise_not_found")
    return exercise, entry


def report(course_id: str, user_id: str, exercise_id: str, body: dict) -> dict:
    """"Report a problem": the exercise is withdrawn from the pool until the instructor has looked at it."""
    require_open(course_id)
    owner = _owner(course_id, user_id)
    reason = body.get("reason")
    if reason not in exercises.REPORT_REASONS:
        raise PracticeError(400, "bad_request", field="reason")
    with storage.locked(course_id):
        exercise, entry = _entry(course_id, owner, exercise_id)
        if entry["reported"]:
            return {"ok": True}
        exercises.set_status(course_id, exercise_id, "retirado" if exercise["status"] == "retirado" else "reportado",
                             report=reason)
        record = progress.load(course_id, owner)
        record["exercises"][exercise_id]["reported"] = True
        progress.save(course_id, owner, record)
    return {"ok": True}


# ── The instructor's view of practice ─────────────────────────────────────────

def _topic_names(course_id: str) -> dict[str, str]:
    return {topic["topic_id"]: topic["name"] or _pages_name(topic) for topic in _merged(course_id)}


def _pages_name(topic: dict) -> str:
    return f"pp. {topic['pages'][0]}-{topic['pages'][1]}" if topic.get("pages") else topic["topic_id"]


def pool(course_id: str) -> dict:
    """Every exercise of the course, newest first, with everything it holds, and every discarded one."""
    names = _topic_names(course_id)
    listed = []
    for exercise in reversed(exercises.all_exercises(course_id)):
        if exercise["type"] == programmed.KIND:
            continue                            # made by a program for one student: see the tutors instead
        view = {**exercise, "topic": names.get(exercise["topic_id"])}
        if exercise["type"] == "numerica":
            answer = exercise["answer"]
            view["answer"] = {**answer, "value_text": exercise_types.shown(answer["value"]),
                              "checked_text": exercise_types.shown(answer.get("checked_value", answer["value"]))}
        listed.append(view)
    rejected = [{**entry, "topic": names.get(entry["topic_id"])} for entry in reversed(exercises.rejections(course_id))]
    return {"exercises": listed, "rejections": rejected}


def retire(course_id: str, exercise_id: str) -> dict:
    if exercises.set_status(course_id, exercise_id, "retirado") is None:
        raise PracticeError(404, "exercise_not_found")
    return {"ok": True}


def approve(course_id: str, exercise_id: str) -> dict:
    """A reported exercise goes back into service. Only a reported one: a retired exercise stays retired."""
    with storage.locked(course_id):
        exercise = exercises.load(course_id, exercise_id)
        if exercise is None:
            raise PracticeError(404, "exercise_not_found")
        if exercise["status"] != "reportado":
            raise PracticeError(409, "not_reported")
        exercises.set_status(course_id, exercise_id, "servido")
    return {"ok": True}


def tutors_review(course_id: str) -> dict:
    """Each programmed tutor as the instructor reviews it: its spec, where it rests in the handout, what it found."""
    return {"min_group": config.min_group(),
            "tutors": programmed.review(course_id, progress.tutor_detections(course_id, _lookup(course_id)),
                                       _topic_names(course_id))}


def class_summary(course_id: str) -> dict:
    names = _topic_names(course_id)
    order = {topic_id: number for number, topic_id in enumerate(names)}
    found = progress.summary(course_id, names, _lookup(course_id))
    found["rows"].sort(key=lambda row: (order.get(row["topic_id"], len(order)), LEVELS.index(row["level"])))
    return found
