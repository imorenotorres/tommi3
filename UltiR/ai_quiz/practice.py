"""Practice ("Practicar"): a student chooses a topic or a level, gets one exercise at a time, answers
it in their own words and gets feedback on it.

This is formative practice and follows its own rule: exercises and feedback reach students as the
model writes them, without an instructor reading them first. What stands in for that reading is
the checks in code (exercise_types, feedback), the label "generated by AI from the handout" on
every exercise, the student's "Report a problem", and the instructor's list of every exercise with
"retire" and "approve". Quizzes keep their rule: nothing reaches students unpublished.

Layout inside a course folder:

    practice/settings.json      {"enabled": bool, "topics": {topic_id: {"enabled": bool, "name": str}}}

Practice exists on a server only when config.practice_enabled(), and in a course only once its
instructor switches it on.
"""

from UltiR.ai_quiz import config, schema, storage, topics

MAX_TOPIC_NAME_CHARS = 80
LEVELS = ("basico", "intermedio", "avanzado")


class PracticeError(Exception):
    def __init__(self, status: int, code: str, **extra):
        super().__init__(code)
        self.status = status
        self.code = code
        self.extra = extra


def _dir(course_id: str):
    return storage.course_dir(course_id) / "practice"


# ── Settings (instructor) ─────────────────────────────────────────────────────

def _settings_path(course_id: str):
    return _dir(course_id) / "settings.json"


def settings(course_id: str) -> dict:
    stored = storage.read_json(_settings_path(course_id), default={}) or {}
    return {"enabled": stored.get("enabled") is True, "topics": stored.get("topics") or {}}


def _merged(course_id: str) -> list[dict]:
    """Every topic found in the course's documents, with what the instructor set for it.

    A topic is on unless the instructor turned it off. Its name is the instructor's, or the
    heading it was found under; a topic made of a range of pages has no name of its own.
    """
    chosen = settings(course_id)["topics"]
    merged = []
    for topic in topics.course_topics(course_id):
        own = chosen.get(topic["topic_id"]) or {}
        merged.append({**topic, "enabled": own.get("enabled") is not False, "name": own.get("name") or topic["title"]})
    return merged


def instructor_settings(course_id: str) -> dict:
    return {
        "enabled": settings(course_id)["enabled"],
        "topics": [{key: topic[key] for key in ("topic_id", "doc_label", "title", "name", "kind", "pages", "enabled")}
                   for topic in _merged(course_id)],
    }


def change_settings(course_id: str, body: dict) -> dict:
    """Switch practice on or off, and topics on or off or rename them. Reads `enabled` and `topics` only.

    `topics` maps a topic id to {"enabled": bool, "name": str}, each optional; an empty name gives
    the topic back the name it was found under. A topic id that is not a topic of the course is refused.
    """
    enabled = body.get("enabled")
    if enabled is not None and not isinstance(enabled, bool):
        raise PracticeError(400, "bad_request", field="enabled")
    changes = body.get("topics", {})
    if not isinstance(changes, dict) or not all(isinstance(c, dict) for c in changes.values()):
        raise PracticeError(400, "bad_request", field="topics")
    if enabled is None and not changes:
        raise PracticeError(400, "bad_request", field="enabled")
    with storage.locked(course_id):
        known = {topic["topic_id"] for topic in topics.course_topics(course_id)}
        if not set(changes) <= known:
            raise PracticeError(404, "unknown_topic")
        current = settings(course_id)
        for topic_id, change in changes.items():
            own = dict(current["topics"].get(topic_id) or {})
            if "enabled" in change:
                if not isinstance(change["enabled"], bool):
                    raise PracticeError(400, "bad_request", field="topics")
                own["enabled"] = change["enabled"]
            if "name" in change:
                try:
                    own["name"] = schema.clean_text(change["name"], MAX_TOPIC_NAME_CHARS, required=False)
                except schema.InvalidQuestion:
                    raise PracticeError(400, "bad_request", field="topics") from None
            current["topics"][topic_id] = own
        if enabled is not None:
            current["enabled"] = enabled
        storage.write_json(_settings_path(course_id), current)
    return instructor_settings(course_id)


# ── What a student may see ────────────────────────────────────────────────────

def require_open(course_id: str) -> None:
    """Practice is on in this course, or PracticeError."""
    if not settings(course_id)["enabled"]:
        raise PracticeError(409, "practice_off")


def open_topics(course_id: str) -> list[dict]:
    """The topics a student can choose: those that are on, with their name, document and pages."""
    return [topic for topic in _merged(course_id) if topic["enabled"]]


def student_topics(course_id: str) -> list[dict]:
    require_open(course_id)
    return [{key: topic[key] for key in ("topic_id", "name", "doc_label", "pages")} for topic in open_topics(course_id)]


def server_offers_practice() -> bool:
    return config.practice_enabled()
